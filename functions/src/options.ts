/**
 * Глобальные настройки всех Cloud Functions проекта.
 *
 * ⚠️ Этот модуль обязан импортироваться ПЕРВЫМ в `index.ts`, до любых других
 * импортов и реэкспортов. Иначе регион не применится к подмодулям.
 *
 * Почему так. В ES-модулях все объявления `import` и `export ... from`
 * вычисляются до того, как выполнится хоть одна строка тела модуля. Раньше
 * вызов `setGlobalOptions` стоял в `index.ts` строкой 19, а реэкспорты
 * подмодулей — строками 8–15. К моменту вызова `telegramBot`, `stepper`,
 * `consents`, `retention` и `referralFunctions` уже успевали объявить свои
 * функции — и получали регион по умолчанию, us-central1.
 *
 * Итог был такой: функции, объявленные прямо в `index.ts` ниже вызова, ехали
 * в europe-west1, а всё из подмодулей — в us-central1. Годами. Из-за этого
 * `telegramWebhook`, шагомер и рефералка жили в старом регионе, а страница
 * `/referral` на сайте не работала вообще: клиент прибит к europe-west1
 * (`src/lib/firebase.ts`), а функции там не было.
 *
 * Отдельным модулем, а не первой строкой в `index.ts`, — именно чтобы порядок
 * нельзя было сломать случайно, переставив импорты местами: линтеры и
 * автоформаттеры любят их сортировать.
 */

