// Ступени потолка ставки в казино.
//
// Потолок считается от общего банка, а сумму банка игрокам не показываем ни
// прямо, ни косвенно (решение Ориона). Точный потолок её выдаёт: у монетки
// банк — 19 потолков, у Плинко — тысяча. Поэтому потолок округляется вниз до
// ступени, и по ней виден только диапазон банка.
//
// Модуль без зависимостей: через plinko.ts он попадает и в браузерную сборку.

/** Ступени потолка ставки, по возрастанию. */
export const BET_TIERS: readonly number[] = [10, 50, 100, 250, 500, 1000, 2500, 5000];

/**
 * Наибольшая ступень, не превышающая лимит. Меньше первой ступени — 0.
 * @param {number} limit потолок, посчитанный от банка
 * @return {number} потолок для игрока
 */
export function betTier(limit: number): number {
  let tier = 0;
  for (const step of BET_TIERS) {
    if (step <= limit) tier = step;
  }
  return tier;
}
